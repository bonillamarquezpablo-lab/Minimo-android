'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const workflow=fs.readFileSync('.github/workflows/coastal-reference.yml','utf8');
const rs=fs.readFileSync('scripts/run-unified-inspector.mjs','utf8');
const center=fs.readFileSync('.github/workflows/inspector-center-checks.yml','utf8');
const hrafn=fs.readFileSync('.github/workflows/hrafn-geometry-measurements.yml','utf8');
const validate=fs.readFileSync('.github/workflows/validate-pr.yml','utf8');
assert.match(workflow,/cancel-in-progress: false/);
assert.match(workflow,/Manual runs are isolated by selected branch and exact commit/);
assert.match(workflow,/group: scene-capture-s26-graphics-.*github\.sha/);
assert.match(workflow,/workflow_dispatch:/);
const mainTriggers=workflow.slice(workflow.indexOf('on:\n'),workflow.indexOf('\npermissions:'));
assert.ok(!/^  (push|pull_request):/m.test(mainTriggers),'The full Inspector must not run on every push or pull request.');
const hrafnTriggers=hrafn.slice(hrafn.indexOf('on:\n'),hrafn.indexOf('\npermissions:'));
assert.ok(hrafnTriggers.includes('workflow_dispatch:')&&!/^  pull_request:/m.test(hrafnTriggers),'Hrafn measurements must also be manual-only.');
assert.match(validate,/pull_request:/,'Ordinary pull-request validation must remain enabled.');
assert.ok(workflow.includes('default: quick'),'Quick must be the default workflow level.');
assert.match(workflow,/CAPTURE_PLAN_INPUT/);
assert.match(workflow,/if \[ "\$GITHUB_EVENT_NAME" = "workflow_dispatch" \] && \[ -n "\$CAPTURE_PLAN_INPUT" \]; then/);
assert.match(workflow,/cat scripts\/scene-capture-plan\.json/);
assert.match(workflow,/default: ''/);
assert.ok(workflow.includes("if: github.event_name == 'workflow_dispatch' && inputs.inspection_level == 'deep'"),'Baseline comparison is available only for a manually requested deep audit.');
assert.ok(workflow.includes("INSPECTOR_LEVEL: ${{ inputs.inspection_level || 'quick' }}"),'A manually requested inspection defaults to Quick.');
assert.match(workflow,/git fetch --no-tags origin "\$BASE_REF"/);
assert.match(workflow,/git rev-parse "\$GITHUB_SHA\^"/);
assert.match(workflow,/for attempt in \$\(seq 1 32\); do/);
assert.match(workflow,/CANDIDATE_VERSION=/);
assert.match(workflow,/BASELINE_VERSION=/);
assert.match(workflow,/Skipping baseline .*same game release/);
assert.match(workflow,/No distinct buildable baseline found in the 32-commit recovery window/);
assert.match(workflow,/node scripts\/test_graphics_quality_contract\.cjs/);
assert.match(workflow,/node scripts\/test_hrafn_before_after_contract\.cjs/);
assert.doesNotMatch(workflow,/feature\/unified-atmosphere-system|manual-game-test-no-inspector|pull_request\.number\s*[!=]=\s*121/);
assert.match(center,/branches: \[main\]/);
assert.doesNotMatch(center,/feature\/inspector-center-dashboard|feature\/tiered-inspector-levels/);
assert.ok(rs.includes("child.once('exit'"),'Inspector phases must settle on child exit rather than waiting for inherited stdio close.');
console.log('Inspector workflow routing and baseline fallback contract: OK');
